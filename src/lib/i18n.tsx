type I18nContextValue = {
  language: UiLanguage;
  setLanguage: (language: UiLanguage) => void;
  t: (source: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);
const defaultI18n: I18nContextValue = {
  language: detectSystemLanguage(),
  setLanguage: () => undefined,
  t: (source) => source,
};

export function I18nProvider({ children, initialLanguage = detectSystemLanguage() }: { children: ReactNode; initialLanguage?: UiLanguage }) {
  const [language, setLanguage] = useState<UiLanguage>(initialLanguage);
  const translate = useCallback((source: string) => language === "en" ? englishTranslations[source] ?? source : source, [language]);
  const value = useMemo(() => ({ language, setLanguage, t: translate }), [language, translate]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext) ?? defaultI18n;
}

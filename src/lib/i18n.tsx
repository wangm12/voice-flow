export type UiLanguage = "zh" | "en";
export type UiLanguagePreference = UiLanguage | "system";

export function detectSystemLanguage(): UiLanguage {
  const languages = typeof navigator !== "undefined" ? navigator.languages : undefined;
  const preferred = languages?.[0] ?? (typeof navigator !== "undefined" ? navigator.language : "");
  return preferred.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function resolveUiLanguage(preference: UiLanguagePreference): UiLanguage {
  return preference === "system" ? detectSystemLanguage() : preference;
}

